NATIVE_TOOL_NAMES: tuple[str, ...] = tuple(s["name"] for s in NATIVE_TOOL_SCHEMAS)

def register_native_tools(registry, executor):
    from .registry import Tool
    for schema in NATIVE_TOOL_SCHEMAS:
        name = schema["name"]
        def _handler(tool_input, _name=name):
            if _name == "Task":
                raise RuntimeError("Task is handled by the session runtime")
            return executor.invoke(_name, tool_input)
        registry.register(Tool(
            name=name,
            description=schema["description"],
            input_schema=schema["input_schema"],
            handler=_handler,
            permission=NATIVE_TOOL_PERMISSIONS.get(name, "execute"),
            category="native",
            origin="native",
        ))
