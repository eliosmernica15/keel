"""Repository scanner and AGENTS.md generator for ``keel init`` (A1.5).

The generated file is plain Markdown with detected layout and commands; it is
a starting point for humans to refine, not a claim about the project.
"""

from __future__ import annotations

from pathlib import Path

SKIP_DIRS = frozenset({
    ".git", ".hg", ".svn", "node_modules", ".venv", "venv", "env",
    "__pycache__", ".pytest_cache", ".mypy_cache", "dist", "build",
    "release", ".idea", ".vscode",
})

MANIFESTS = (
    "pyproject.toml", "requirements.txt", "setup.py", "setup.cfg",
    "package.json", "Cargo.toml", "go.mod", "pom.xml", "Makefile",
    "CMakeLists.txt", "AGENTS.md", "README.md",
)


def scan_project(cwd: str | Path) -> dict:
    root = Path(cwd).resolve()
    manifests = [name for name in MANIFESTS if (root / name).is_file()]
    directories = sorted(
        p.name for p in root.iterdir()
        if p.is_dir() and p.name not in SKIP_DIRS)[:20]
    top_level_files = sorted(
        p.name for p in root.iterdir()
        if p.is_file() and not p.name.startswith("."))[:30]
    test_dirs = [d for d in ("tests", "test", "spec") if d in directories]
    return {"root": str(root), "manifests": manifests,
            "directories": directories, "test_dirs": test_dirs,
            "top_level_files": top_level_files}


def detect_commands(scan: dict) -> list[str]:
    manifests = set(scan.get("manifests", []))
    commands = []
    if {"pyproject.toml", "requirements.txt", "setup.py"} & manifests:
        commands.append("python -m pytest -q")
    if "package.json" in manifests:
        commands += ["npm test", "npm run lint"]
    if "Makefile" in manifests:
        commands.append("make test")
    if "Cargo.toml" in manifests:
        commands.append("cargo test")
    if "go.mod" in manifests:
        commands.append("go test ./...")
    return commands


def render_agents_md(scan: dict) -> str:
    lines = [
        "# AGENTS.md",
        "",
        "Generated by `keel init`. Refine this file and commit it so every",
        "agent receives the same project context.",
        "",
        "## Project layout",
        "",
    ]
    if scan["directories"]:
        lines += [f"- `{d}/`" for d in scan["directories"]]
    else:
        lines.append("- (no top-level directories detected)")
    if scan["top_level_files"]:
        lines += ["", "Top-level files: " + ", ".join(
            f"`{name}`" for name in scan["top_level_files"])]
    lines += ["", "## Build and verification commands", ""]
    commands = detect_commands(scan)
    if commands:
        lines += [f"- `{command}`" for command in commands]
    else:
        lines.append("- (none detected — add the commands you use)")
    lines += [
        "",
        "## Working rules",
        "",
        "- Keep changes local and focused; do not commit unless asked.",
        "- Run the verification commands above after code changes.",
        "- Use recoverable operations for destructive file actions.",
        "- Report evidence for claims of completion.",
        "",
    ]
    return "\n".join(lines)


def write_agents_md(cwd: str | Path, *, force: bool = False) -> Path:
    root = Path(cwd).resolve()
    target = root / "AGENTS.md"
    if target.exists() and not force:
        raise FileExistsError(f"{target} already exists (use --force to replace)")
    scan = scan_project(root)
    target.write_text(render_agents_md(scan), encoding="utf-8")
    return target
