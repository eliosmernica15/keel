"use strict";

/* Keel desktop — renderer. Works standalone in a browser (demo mode, clearly
   labelled) or inside Tauri against the real keel sidecar (`window.__TAURI__`). */

const $ = (id) => document.getElementById(id);
const transcript = $("transcript");
const promptEl = $("prompt");
const sendBtn = $("send-btn");

const state = { running: false, sessionId: null, turns: 0, tokens: 0 };

/* ------------------------------------------------------------ bridges */

function mkBridge() {
  if (window.__TAURI__) {
    return {
      live: true,
      send(payload) {
        return window.__TAURI__.core.invoke("keel_send", payload);
      },
      listen(event, cb) {
        return window.__TAURI__.event.listen(event, cb);
      },
      providers() {
        return window.__TAURI__.core.invoke("keel_providers")
          .then((rows) => rows)
          .catch(() => []);
      },
    };
  }
  if (location.protocol === "http:" || location.protocol === "https:") {
    // local webapp bridge (see src/keel/webapp.py)
    const params = new URLSearchParams(location.search);
    const token = params.get("t") || sessionStorage.getItem("keel_token") || "";
    if (token) sessionStorage.setItem("keel_token", token);
    const headers = () => ({ "X-Keel-Token": token });
    const trimmedQuery = () => {
      const url = new URL(location.href);
      url.searchParams.delete("t");
      history.replaceState(null, "", url.pathname + url.search);
    };
    return {
      live: true,
      send(payload) {
        return fetch("/api/run", {
          method: "POST",
          headers: {
            ...headers(),
            "Content-Type": "application/json",
          },
          body: JSON.stringify(payload),
        }).then(async (resp) => {
          if (!resp.ok || !resp.body) {
            const text = await resp.text().catch(() => "");
            throw new Error(`http ${resp.status} ${text.slice(0, 300)}`);
          }
          trimmedQuery();
          const reader = resp.body.getReader();
          const decoder = new TextDecoder();
          let buffer = "";
          while (true) {
            const { done, value } = await reader.read();
            if (done) break;
            buffer += decoder.decode(value, { stream: true });
            const lines = buffer.split("\n");
            buffer = lines.pop() || "";
            for (const line of lines) {
              if (!line.trim()) continue;
              try { handleEvent(JSON.parse(line)); } catch { /* skip */ }
            }
          }
          if (buffer.trim()) {
            try { handleEvent(JSON.parse(buffer)); } catch { /* skip */ }
          }
          return "bridge";
        });
      },
      providers() {
        return fetch("/api/providers", { headers: headers() })
          .then((r) => r.ok ? r.json() : { providers: [] })
          .then((doc) => doc.providers || [])
          .catch(() => []);
      },
      listen() { return Promise.resolve(() => {}); },
    };
  }
  // Standalone file:// fallback: clearly labeled fixture demo
  return {
    live: false,
    send(payload) {
      const plan = [
        { type: "system", subtype: "init", session_id: "demo-0001",
          tools: ["read_file", "write_file", "edit_file", "glob", "grep", "run_shell"],
          model: "demo (not a real model)", permissionMode: payload.permission_mode },
        { type: "assistant", message: { content: [
          { type: "tool_use", id: "call_demo1", name: "run_shell",
            input: { command: "echo demo: it ran a shell command", shell: "posix" } } ] } },
        { type: "user", message: { content: [
          { type: "tool_result", tool_use_id: "call_demo1",
            content: "demo output (mock backend — no process was executed)" } ] } },
        { type: "assistant", message: { content: [
          { type: "text", text: "[demo mode] This transcript is generated by a built-in fixture; no model and no keel backend are connected. Start `keel serve` and open the printed URL for the real thing." } ] } },
        { type: "result", subtype: "success", is_error: false, num_turns: 1,
          total_cost_usd: 0, usage: { input_tokens: 0, output_tokens: 0 },
          stop_reason: "end_turn", terminal_reason: "completed",
          result: "demo run complete", session_id: "demo-0001" },
      ];
      for (const evt of plan) handleEvent(evt);
      finishRun();
      return Promise.resolve("demo");
    },
    listen() { return Promise.resolve(() => {}); },
    providers() { return Promise.resolve([]); },
  };
}

const bridge = mkBridge();

/* --------------------------------------------------------- rendering */

function el(tag, props, ...children) {
  const node = document.createElement(tag);
  Object.assign(node, props || {});
  for (const child of children) {
    if (child == null) continue;
    node.appendChild(typeof child === "string" ? document.createTextNode(child) : child);
  }
  return node;
}

function appendMessage(kind, role, build) {
  const msg = el("div", { className: `msg ${kind}` });
  msg.appendChild(el("small", { className: "role", textContent: role }));
  const body = el("div", { className: "body" });
  build(body);
  msg.appendChild(body);
  transcript.appendChild(msg);
  transcript.scrollTop = transcript.scrollHeight;
  return msg;
}

function systemNote(text, cls = "system") {
  appendMessage(cls, "system", (body) => { body.textContent = text; });
}

function renderToolUse(block) {
  appendMessage("tool", "tool call", (body) => {
    const box = el("div", { className: "tool-call" });
    box.appendChild(el("span", { className: "tool-name",
                                 textContent: String(block.name) }));
    box.appendChild(document.createTextNode("  " + JSON.stringify(block.input || {})));
    body.appendChild(box);
  });
}

function renderToolResult(block) {
  const text = String(block.content ?? "");
  const isError = text.startsWith("<tool_use_error>");
  appendMessage(isError ? "denied" : "tool", "tool result", (body) => {
    const pre = el("div", { className: isError ? "tool-result-error" : "tool-call",
                            textContent: text.slice(0, 4000) });
    body.appendChild(pre);
  });
}

function renderResult(evt) {
  const u = evt.usage || {};
  state.tokens += (u.input_tokens || 0) + (u.output_tokens || 0);
  state.turns = evt.num_turns ?? state.turns + 1;
  appendMessage("result", "result", (body) => {
    const grid = el("div", { className: "result-grid" });
    const cell = (label, value) => {
      const div = el("div");
      div.appendChild(el("span", { textContent: label }));
      div.appendChild(el("strong", { textContent: String(value) }));
      grid.appendChild(div);
    };
    cell("turns", evt.num_turns ?? 0);
    cell("tokens", (u.input_tokens || 0) + (u.output_tokens || 0));
    cell("cost", `$${(evt.total_cost_usd ?? 0).toFixed(4)}`);
    cell("stop", evt.stop_reason ?? "?");
    cell("is error", evt.is_error ? "yes" : "no");
    body.appendChild(grid);
  });
  $("turn-count").textContent = `${evt.num_turns ?? state.turns} turns`;
  $("token-count").textContent = `${state.tokens} tokens`;
}

function handleEvent(evt) {
  switch (evt.type) {
    case "system": {
      const sub = evt.subtype;
      if (sub === "init") {
        state.sessionId = evt.session_id;
        $("session-id-label").textContent = `session ${String(evt.session_id).slice(0, 8)}`;
        const toolCount = Array.isArray(evt.tools) ? evt.tools.length : 0;
        const mcp = Array.isArray(evt.mcp_servers) ? evt.mcp_servers.length : 0;
        systemNote(`session started — ${toolCount} tools, ${mcp} MCP server(s), model ${evt.model}`);
        return;
      }
      if (sub === "permission_denied") {
        systemNote(`permission denied: ${evt.tool_name} — ${evt.decision_reason}`, "denied");
        return;
      }
      if (sub === "informational" || sub === "compact_boundary") {
        systemNote(evt.content || JSON.stringify(evt));
        return;
      }
      if (sub === "hook_response") {
        systemNote(`hook ${evt.hook_name}: ${evt.verdict}`);
        return;
      }
      return;
    }
    case "assistant": {
      const blocks = evt.message?.content || [];
      for (const block of blocks) {
        if (block.type === "text") {
          appendMessage("assistant", "assistant", (body) => {
            body.textContent = block.text;
          });
        } else if (block.type === "tool_use") {
          renderToolUse(block);
        } else if (block.type === "thinking") {
          appendMessage("system", "thinking", (body) => {
            body.textContent = block.thinking || block.text || "";
          });
        }
      }
      return;
    }
    case "user": {
      for (const block of evt.message?.content || []) {
        if (block.type === "tool_result") renderToolResult(block);
      }
      return;
    }
    case "result":
      renderResult(evt);
      finishRun();
      return;
  }
}

/* ---------------------------------------------------------- control flow */

function setStatus(text, kind) {
  $("status-text").textContent = text;
  const dot = $("status-dot");
  dot.className = `dot ${kind === "busy" ? "dot-busy" : kind === "err" ? "dot-err" : "dot-ok"}`;
}

function finishRun() {
  state.running = false;
  sendBtn.disabled = false;
  setStatus("idle", "ok");
}

function startRun() {
  state.running = true;
  sendBtn.disabled = true;
  setStatus("running…", "busy");
}

function send() {
  const prompt = promptEl.value.trim();
  if (!prompt || state.running) return;

  const provider = $("provider-select").value;
  const permission_mode = $("mode-select").value;
  const acceptRisk = $("accept-risk").checked;
  if (permission_mode === "bypassPermissions" && !acceptRisk) {
    systemNote("bypass mode requires 'I accept the risk' before sending", "denied");
    return;
  }

  appendMessage("user", "you", (body) => { body.textContent = prompt; });
  startRun();

  const payload = { prompt, provider, permission_mode, accept_risk: acceptRisk };
  const maybePromise = bridge.send(payload);
  if (maybePromise && maybePromise.catch) {
    maybePromise.catch((err) => {
      systemNote(`backend error: ${err}`, "denied");
      finishRun();
    });
  }
  promptEl.value = "";
}

$("prompt-form").addEventListener("submit", (ev) => { ev.preventDefault(); send(); });

promptEl.addEventListener("keydown", (ev) => {
  if (ev.key === "Enter" && !ev.shiftKey) { ev.preventDefault(); send(); }
});

$("mode-select").addEventListener("change", (ev) => {
  $("mode-pill").textContent = ev.target.options[ev.target.selectedIndex].text;
});
$("provider-select").addEventListener("change", (ev) => {
  $("provider-pill").textContent = `provider: ${ev.target.value}`;
});

$("copy-transcript").addEventListener("click", () => {
  const text = [...transcript.querySelectorAll(".msg")]
    .map((m) => `[${m.querySelector(".role")?.textContent || "?"}] ${m.querySelector(".body")?.textContent || ""}`)
    .join("\n\n");
  navigator.clipboard?.writeText(text).catch(() => {});
});
$("clear-transcript").addEventListener("click", () => { transcript.innerHTML = ""; });

/* -------------------------------------------------------------- startup */

$("provider-pill").textContent = `provider: auto`;
$("mode-pill").textContent = "manual";

if (!bridge.live) {
  systemNote("demo mode — open the URL printed by `keel serve` for the real backend", "system");
} else {
  bridge.listen("keel:event", (message) => {
    // Tauri passes an event object ({ payload: "<line>" }); the browser mock passes a raw line
    const line = typeof message === "string" ? message :
      (message && typeof message.payload === "string" ? message.payload : "");
    try { handleEvent(JSON.parse(line)); } catch { /* skip malformed line */ }
  });
  bridge.listen("keel:done", () => finishRun());
  // live key status from the local bridge
  bridge.providers().then((rows) => {
    for (const row of rows) {
      const item = document.querySelector(`.key-list li[data-key="KEEL_${row.name.toUpperCase().replace(/-/g, "_")}_API_KEY"]`);
      if (item) {
        const state = item.querySelector(".key-state");
        state.textContent = row.configured ? "set" : "unset";
        state.classList.toggle("on", row.configured);
      }
    }
  }).catch(() => {});
}

// PWA: register the app-shell service worker (only over http(s))
if ("serviceWorker" in navigator && location.protocol.startsWith("http")) {
  navigator.serviceWorker.register("/sw.js").catch(() => {});
}
